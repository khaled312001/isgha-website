// يولّد docs/IMAGE-PROMPTS.md من خانات صور الموقع (نفس البرومبتات الظاهرة في لوحة التحكم)
// التشغيل: npm run docs:images
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { IMAGE_SLOTS, IMAGE_STYLE, IMAGE_NEGATIVE, EXTRA_PROMPTS } from '../src/content/image-slots.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ar = (n) => String(n).replace(/\d/g, (d) => '٠١٢٣٤٥٦٧٨٩'[d]);

const out = [];
const p = (s = '') => out.push(s);

p('# برومبتات صور موقع إصغاء للمحاماة');
p();
p('دليل توليد صور الموقع بالذكاء الاصطناعي بهوية سعودية راقية تتناسق مع ألوان إصغاء. لكل صورة: مكان ظهورها، المقاس، وصف المشهد، ملاحظات القصّ، والبرومبت الكامل جاهزًا للنسخ.');
p();
p('> البرومبتات نفسها موجودة في **لوحة التحكم ← صور الموقع** مع زر نسخ وزر رفع لكل خانة. بعد رفع الصورة تظهر في الموقع فورًا.');
p();
p('## الاتجاه البصري');
p();
p('- **الإحساس:** فخامة هادئة (Quiet luxury) بأسلوب مجلات الأعمال الراقية؛ لقطات طبيعية غير متكلفة، بلا ابتسامات مصطنعة ولا مصافحات تقليدية.');
p('- **الألوان:** عاجي دافئ، بيج الترافرتين، أخضر تركوازي عميق، فحمي، ولمسات نحاس مطفأ — نفس ألوان الشعار والموقع.');
p('- **المواد:** حجر الترافرتين، خشب الجوز، الجلد الأخضر الداكن، المخمل التركوازي، النحاس، الكتان.');
p('- **الهوية السعودية:** الثوب الأبيض بياقة مرتبة، الغترة البيضاء أو الشماغ الأحمر بعقال أسود مستوٍ، البشت للشخصيات الكبيرة، البدلات الرسمية الكحلية والفحمية، العمارة النجدية والفتحات المثلثة، النقوش الهندسية الخشبية، الدلة والفنجان، نقش السدو بلمسة خفيفة، أفق الرياض والمركز المالي.');
p('- **الضوء:** ضوء نهار طبيعي ناعم من النوافذ، ظلال هادئة منخفضة التباين، وضوء ذهبي للمشاهد الخارجية.');
p();
p('### تجنّب دائمًا');
p();
p('- أي كتابة أو شعارات أو أعلام أو شعارات حكومية (لتجنب أي إشكال نظامي).');
p('- المطرقة القضائية وباروكة القاضي وقاعات المحاكم الغربية — غير مستخدمة في المحاكم السعودية.');
p('- الغترة أو العقال بشكل خاطئ أو مائل — راجع هذا التفصيل في كل صورة قبل اعتمادها.');
p('- الأيدي المشوهة أو الأصابع الزائدة — كبّر الصورة وافحص الأيدي جيدًا.');
p();
p('## طريقة الاستخدام');
p();
p('1. انسخ البرومبت الكامل للصورة (يتضمن الأسلوب الموحّد في نهايته).');
p('2. **Midjourney:** الصق البرومبت ثم أضف الإعدادات المكتوبة تحته (مثل `--ar 4:5 --style raw`) والبرومبت السلبي بعد `--no`.');
p('3. **Gemini / Imagen / ChatGPT / Firefly:** الصق البرومبت كما هو واكتب في النهاية: «نسبة الصورة 4:5» حسب الخانة، وأضف: «Avoid: …» مع البرومبت السلبي.');
p('4. **ثبات الشخصية:** ولّد صورة «الترويسة الرئيسية» أولًا، ثم استخدمها مرجعًا للشخصية في صورة «الاستشارة» (في Midjourney: `--cref رابط_الصورة`، وفي Gemini: ارفع الصورة واطلب «نفس الشخص»).');
p('5. صدّر الصورة بصيغة **WebP** بجودة 80–85٪ وبالمقاس المذكور (يفضّل أقل من 400 كيلوبايت)، ثم ارفعها في خانتها من لوحة التحكم.');
p();
p('## الأسلوب الموحّد (مضاف تلقائيًا لكل برومبت)');
p();
p('```text');
p(IMAGE_STYLE);
p('```');
p();
p('## البرومبت السلبي (Negative prompt)');
p();
p('```text');
p(IMAGE_NEGATIVE);
p('```');
p();
p('## ملخص الصور المطلوبة');
p();
p('| # | الصورة | مكان الظهور | المقاس | النسبة |');
p('|---|---|---|---|---|');
IMAGE_SLOTS.forEach((s, i) => p(`| ${ar(i + 1)} | ${s.label} | ${s.page} | ${s.size} | ${s.ratio} |`));
p();

IMAGE_SLOTS.forEach((s, i) => {
  p('---');
  p();
  p(`## ${ar(i + 1)}. ${s.label}`);
  p();
  p(`- **مكان الظهور:** ${s.page}`);
  p(`- **المقاس:** ${s.size} بكسل · **النسبة:** ${s.ratio}`);
  p(`- **اسم الملف المقترح:** \`${s.file}\``);
  p(`- **النص البديل (Alt):** ${s.alt}`);
  p();
  p(`**المشهد:** ${s.scene}`);
  p();
  if (s.notes) { p(`**ملاحظات القص والتكوين:** ${s.notes}`); p(); }
  p('**البرومبت:**');
  p();
  p('```text');
  p(s.prompt);
  p('```');
  p();
  p(`**إعدادات Midjourney:** \`${s.mj} --no ${IMAGE_NEGATIVE.split(', ').slice(0, 12).join(', ')}\``);
  p();
  if (s.variant) { p(`**بديل:** ${s.variant}`); p(); }
});

p('---');
p();
p('## صور إضافية اختيارية');
p();
p('أغلفة للمقالات حسب التصنيف (ترفع من صفحة تعديل المقال ← صورة الغلاف):');
p();
EXTRA_PROMPTS.forEach((e) => {
  p(`### ${e.title} (${e.size} · ${e.ratio})`);
  p();
  p('```text');
  p(`${e.subject} ${IMAGE_STYLE}`);
  p('```');
  p();
});
p('### صور فريق العمل');
p();
p('صور أعضاء الفريق يجب أن تكون **صورًا حقيقية** لهم (لا تُولَّد بالذكاء الاصطناعي). للحصول على مظهر موحّد اطلب من المصوّر: خلفية جدار جصي عاجي، ضوء نافذة جانبي ناعم، لقطة نصفية بنسبة 4:5، الثوب والغترة والعقال أو البدلة الرسمية، وتعبير هادئ واثق.');
p();
p('> الصور المولّدة بالذكاء الاصطناعي توضيحية للأجواء فقط؛ لا تُقدَّم على أنها صور لموظفين أو عملاء حقيقيين.');
p();

const file = path.join(ROOT, 'docs', 'IMAGE-PROMPTS.md');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, `${out.join('\n')}\n`);
console.log(`كُتب ${path.relative(ROOT, file)} (${IMAGE_SLOTS.length} صورة)`);
